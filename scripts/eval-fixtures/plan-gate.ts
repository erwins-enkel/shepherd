// Labelled fixtures for the plan-gate reviewer eval (issue #2156).
//
// What these measure is FINDINGS ROUTING (#1948) and LOCATION REFERENCES — the two blocks that
// exist because the reviewer used to manufacture blocking findings out of wording preferences,
// scope demands and stale line numbers, burning whole rework budgets. Half the set is therefore
// plans that MUST be approved: sound but narrower than the reviewer would have scoped, terse where
// it would have argued, citing line numbers, or naming code it proposes to create. The other half
// are genuine defects the reviewer must still block on.
//
// Every fixture also carries the prompt's own hard contract, applied by the scorer to all of them:
// `approve` requires an EMPTY `findings`; `request-changes` requires at least one.
//
// Plans are deliberately short. The eval measures routing judgement, not the reviewer's stamina.

